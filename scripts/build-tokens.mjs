// Builds dist/tokens.css (values + theme switching) and dist/theme.css (Tailwind v4 @theme)
// from the W3C design token files in tokens/. No dependencies.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(`../tokens/${f}`, import.meta.url)));
const primitives = read("primitives.json");
const semantic = read("semantic.json");
const typography = read("typography.json");
const dark = read("theme.dark.json");
const light = read("theme.light.json");

const NS = "com.alygates.notions";
const flatten = (tree, path = [], out = {}) => {
  for (const [k, v] of Object.entries(tree)) {
    if (k.startsWith("$")) continue;
    if (v && typeof v === "object" && "$value" in v) out[[...path, k].join(".")] = v;
    else flatten(v, [...path, k], out);
  }
  return out;
};
const all = { ...flatten(primitives), ...flatten(semantic), ...flatten(typography) };
const cssName = (path) => all[path]?.$extensions?.[NS]?.css;

// A reference like {color.neutral.900} becomes var(--color-neutral-900).
const toCss = (value) => {
  if (Array.isArray(value)) return value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  if (typeof value !== "string") return String(value);
  return value.replace(/\{([^}]+)\}/g, (_, path) => {
    const name = cssName(path);
    if (name) return `var(${name})`;
    if (all[path]) return toCss(all[path].$value);
    throw new Error(`Unresolved reference {${path}}`);
  });
};

const decl = (name, value) => `  ${name}: ${value};`;
const lines = [];
const header = "/* Generated by scripts/build-tokens.mjs from tokens/. Do not edit by hand. */";

// ---- tokens.css ----
lines.push(header, "", "/* Primitives: raw values. Not Tailwind utilities. */", ":root {");
for (const [path, t] of Object.entries(flatten(primitives))) {
  const name = cssName(path);
  if (name) lines.push(decl(name, toCss(t.$value)));
}
for (const [path, t] of Object.entries(flatten(semantic))) {
  const name = cssName(path);
  if (!name) continue;
  const v = t.$type === "cubicBezier" ? `cubic-bezier(${t.$value.join(", ")})` : toCss(t.$value);
  lines.push(decl(name, v));
}
lines.push("}", "");

const themeBlock = (selector, tree) => {
  lines.push(`${selector} {`);
  for (const t of Object.values(flatten(tree))) {
    const name = t.$extensions[NS].css.replace(/^--color-/, "--notions-");
    lines.push(decl(name, toCss(t.$value)));
  }
  lines.push("}", "");
};
lines.push("/* Semantic colors. Dark is the default; .light switches. */");
themeBlock(":root, .dark", dark);
themeBlock(".light", light);
lines.push("@media (prefers-color-scheme: light) {");
lines.push("  :root:not(.dark) {");
for (const t of Object.values(flatten(light))) {
  lines.push(`  ${decl(t.$extensions[NS].css.replace(/^--color-/, "--notions-"), toCss(t.$value))}`);
}
lines.push("  }", "}", "");

// ---- theme.css ----
const theme = [header, "", "@theme inline {", "  --color-*: initial;", "  --radius-*: initial;", ""];
theme.push("  /* Semantic colors -> bg-*, text-*, border-* utilities */");
for (const t of Object.values(flatten(dark))) {
  const name = t.$extensions[NS].css;
  theme.push(decl(name, `var(${name.replace(/^--color-/, "--notions-")})`));
}
theme.push("", "  /* Radius */");
for (const [k, t] of Object.entries(primitives.radius)) theme.push(decl(`--radius-${k}`, t.$value));
theme.push("", "  /* Icon and control sizes -> size-icon-md, size-control-md */");
for (const g of ["icon", "control"]) for (const [k, t] of Object.entries(primitives.size[g])) theme.push(decl(`--spacing-${g}-${k}`, t.$value));
theme.push("", "  /* Type */");
for (const [k, t] of Object.entries(typography["font-family"])) theme.push(decl(`--font-${k}`, `var(--font-family-${k}, ${toCss(t.$value)})`));
for (const [k, t] of Object.entries(typography["font-size"])) theme.push(decl(`--text-${k}`, t.$extensions?.[NS]?.css_value ?? t.$value));
theme.push(decl("--ease-out", "cubic-bezier(0, 0, 0.2, 1)"));
theme.push("}", "");

mkdirSync(new URL("../dist/", import.meta.url), { recursive: true });
writeFileSync(new URL("../dist/tokens.css", import.meta.url), lines.join("\n"));
writeFileSync(new URL("../dist/theme.css", import.meta.url), theme.join("\n"));
console.log("Built dist/tokens.css and dist/theme.css");
